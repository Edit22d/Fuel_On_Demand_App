// Google Maps key: put `mapsApiKey=AIza...` in android/local.properties, or set the
// GOOGLE_MAPS_API_KEY environment variable in CI. Without it the app renders the
// built-in dark map preview instead of live tiles.
val mapsApiKey: String = run {
    val props = Properties()
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { props.load(it) }
    props.getProperty("mapsApiKey") ?: System.getenv("GOOGLE_MAPS_API_KEY") ?: ""
}

